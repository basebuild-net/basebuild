const converter = OpenCC.Converter({ from: "cn", to: "twp" });
const overrideKeys = [...OVERRIDES.keys()].sort((a, b) => b.length - a.length);
const overridePattern = new RegExp(`(${overrideKeys.join("|")})`, "g");
const CJK = /[\u3400-\u9fff]/;

/** Convert one zh-CN string value. Override terms are split out first so OpenCC never rewrites them. */
export function toZhTW(text) {
  return text
    .split(overridePattern)
    .map((part, i) => (i % 2 === 1 ? OVERRIDES.get(part) : converter(part)))
    .join("");
}

/** Rewrite one zh-CN catalog source file to zh-TW, keeping its layout and comments. */
export function convertCatalogSource(source, fileName) {
  const sf = ts.createSourceFile(fileName, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.TS);
  const edits = [];
  const visit = (node) => {
    if (ts.isPropertyAssignment(node) && ts.isStringLiteral(node.initializer)) {
      const init = node.initializer;
      edits.push({ start: init.getStart(sf), end: init.getEnd(), text: JSON.stringify(toZhTW(init.text)) });
      return;
    }
    if (ts.isStringLiteral(node) && CJK.test(node.text)) {
      throw new Error(`${fileName}:${sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1}: Chinese string outside a catalog entry`);
    }
    if (ts.isIdentifier(node) && /zhCN|ZhCN/.test(node.text)) {
      edits.push({
        start: node.getStart(sf),
        end: node.getEnd(),
        text: node.text.replace(/zhCN/g, "zhTW").replace(/ZhCN/g, "ZhTW"),
      });
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);

  let out = source;
  for (const edit of edits.sort((a, b) => b.start - a.start)) {
    out = out.slice(0, edit.start) + edit.text + out.slice(edit.end);
  }
  return GENERATED_HEADER + out;
}

/** All generated zh-TW files, keyed by file name. */
export function generateZhTW() {
  const files = new Map();
  for (const name of readdirSync(ZH_CN_DIR).filter((f) => f.endsWith(".ts")).sort()) {
    files.set(name, convertCatalogSource(readFileSync(join(ZH_CN_DIR, name), "utf8"), name));
  }
  return files;
}

function main() {
  const files = generateZhTW();
  mkdirSync(ZH_TW_DIR, { recursive: true });
  for (const name of readdirSync(ZH_TW_DIR)) {
    if (!files.has(name)) rmSync(join(ZH_TW_DIR, name));
  }
  for (const [name, content] of files) {
    writeFileSync(join(ZH_TW_DIR, name), content);
  }
  console.log(`generate-zh-hant: wrote ${files.size} files to src/i18n/zh-TW`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
